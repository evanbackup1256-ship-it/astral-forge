"""Upload the rendered art (assets/generated/art), turn each Decal into its image id, and write ArtKit/ArtAssets.ts.

    python tools/assetgen/upload_art.py upload                      Open Cloud upload as Decals; skips unchanged images
    python tools/assetgen/upload_art.py resolve path/to/studio.py   ask a running Studio for each Decal's image id
    python tools/assetgen/upload_art.py write                       write src/Client/AstralForge/ArtKit/ArtAssets.ts

Ids live in assets/asset_ids.json under "Art.<name>" (decal), "Art.<name>.Image" and "Art.<name>.Hash".
"""
from __future__ import annotations

import hashlib
import json
import subprocess
import sys
import tempfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import upload  # noqa: E402
from render_art import ART_LIST  # noqa: E402

ROOT = HERE.parents[1]
IDS = ROOT / "assets" / "asset_ids.json"
ART = ROOT / "assets" / "generated" / "art"
OUT_TS = ROOT / "src" / "Client" / "AstralForge" / "ArtKit" / "ArtAssets.ts"


def digest(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()[:16]


def load_ids() -> dict:
    return json.loads(IDS.read_text(encoding="utf-8")) if IDS.exists() else {}


def save_ids(ids: dict):
    IDS.write_text(json.dumps(ids, indent=2), encoding="utf-8")


def do_upload():
    key = upload.saved("ROBLOX_API_KEY")
    if not key:
        sys.exit("No Open Cloud key yet: run  powershell -ExecutionPolicy Bypass -File tools/assetgen/set-key.ps1")
    ids = load_ids()
    print("uploading as", upload.creator())
    for name in ART_LIST:
        path = ART / f"{name}.png"
        if not path.exists():
            sys.exit(f"{path} is missing: run render_art.py first")
        h = digest(path)
        if ids.get(f"Art.{name}") and ids.get(f"Art.{name}.Hash") == h:
            print(f"{name}: unchanged ({ids[f'Art.{name}']})")
            continue
        print(f"uploading {name} ...")
        ids[f"Art.{name}"] = upload.upload(key, "Decal", str(path), "image/png", f"Astral Forge {name}", "Astral Forge interface artwork.")
        ids[f"Art.{name}.Hash"] = h
        ids.pop(f"Art.{name}.Image", None)
        save_ids(ids)
        print("  ->", ids[f"Art.{name}"])


def do_resolve(studio: str, datamodel: str):
    ids = load_ids()
    names = [n for n in ART_LIST if ids.get(f"Art.{n}") and not ids.get(f"Art.{n}.Image")]
    if not names:
        print("nothing to resolve")
        return
    decals = [ids[f"Art.{n}"] for n in names]
    code = (
        "local out = {} local ids = {" + ",".join(str(d) for d in decals) + "} "
        "for i, id in ids do local ok, model = pcall(function() return game:GetService('InsertService'):LoadAsset(id) end) "
        "local tex = '' if ok and model then local d = model:FindFirstChildWhichIsA('Decal', true) tex = d and d.Texture or '' model:Destroy() end "
        "out[i] = tex end return table.concat(out, ',')"
    )
    with tempfile.NamedTemporaryFile("w", suffix=".json", delete=False, encoding="utf-8") as f:
        json.dump({"datamodel_type": datamodel, "code": code}, f)
        args = f.name
    result = subprocess.run([sys.executable, studio, "execute_luau", "@" + args], capture_output=True, text=True, encoding="utf-8")
    textures = result.stdout.strip().split(",")
    for name, tex in zip(names, textures):
        digits = "".join(ch for ch in tex if ch.isdigit())
        if digits:
            ids[f"Art.{name}.Image"] = int(digits)
            print(f"{name}: image {digits}")
        else:
            print(f"{name}: not resolved yet ({tex!r}); it may still be in moderation, run resolve again shortly")
    save_ids(ids)


def do_write():
    ids = load_ids()
    lines = [
        "// Generated by tools/assetgen/upload_art.py from the designed art in tools/assetgen/art. Do not edit by hand.",
        "// An empty string means that piece is not uploaded yet; callers fall back to drawing without it.",
        "export const ART = {",
    ]
    missing = []
    for name in ART_LIST:
        image = ids.get(f"Art.{name}.Image")
        key = "".join(part.capitalize() for part in name.split("-"))
        lines.append(f'\t{key}: "{"rbxassetid://" + str(image) if image else ""}",')
        if not image:
            missing.append(name)
    lines.append("} as const;")
    lines.append("")
    OUT_TS.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {OUT_TS}" + (f" ({len(missing)} not resolved: {', '.join(missing)})" if missing else ""))


if __name__ == "__main__":
    command = sys.argv[1] if len(sys.argv) > 1 else ""
    if command == "upload":
        do_upload()
    elif command == "resolve":
        do_resolve(sys.argv[2], sys.argv[3] if len(sys.argv) > 3 else "Server")
    elif command == "write":
        do_write()
    else:
        sys.exit(__doc__)
