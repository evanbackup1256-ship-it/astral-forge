"""Build every generated asset and the manifest the game reads.

    python tools/assetgen/build.py              # render everything
    python tools/assetgen/build.py --only kit   # just one part: sfx | ambience | kit
    python tools/assetgen/build.py --manifest   # only rewrite the Luau manifest

Outputs (assets/generated/):
    AstralForgeSFX.wav        every one-shot sound, packed as one sheet
    AstralForgeAmbience.wav   the sanctuary's region loops, packed as one sheet
    AstralForgeKit.glb        every model, one named node each
    build.json                regions, lengths and model sizes

and src/Shared/AstralForge/Shared/AssetManifest.luau, which combines
build.json with the uploaded asset ids in assets/asset_ids.json. Upload with
tools/assetgen/upload.py (or by hand in Studio, then put the ids in
asset_ids.json and run --manifest).
"""

from __future__ import annotations

import json
import math
import os
import sys
import time

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)

import ambience  # noqa: E402
import meshes  # noqa: E402
import sfx  # noqa: E402
from synth import SR, mix, write_wav, zeros  # noqa: E402

ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
OUT = os.path.join(ROOT, "assets", "generated")
IDS = os.path.join(ROOT, "assets", "asset_ids.json")
SUITE = os.path.join(ROOT, "src", "Shared", "AstralForge", "Shared", "SharedData.luau")

GAP = 0.3  # silence between sheet entries, so a region never bleeds into the next


def loudness(buf):
    """RMS in dB over the part of the sound that is actually sounding (above
    -40 dB of its peak), so a long reverb tail doesn't make a voice read quiet."""
    top = max((abs(v) for v in buf), default=0.0)
    floor = top * 0.01
    active = [v for v in buf if abs(v) > floor] or buf
    rms = math.sqrt(sum(v * v for v in active) / max(1, len(active)))
    return round(20 * math.log10(max(rms, 1e-9)), 2)


SFX_GAP = 0.15  # the one-shot sheet: short gaps keep it under Open Cloud's 20 MB upload cap
SFX_RATE = 32000  # and so does writing it at 32 kHz (the cues have nothing above 16 kHz worth keeping)


def resample(buf, rate, regions=None):
    """Band-limited resample (FFT truncation) from SR to `rate`. With `regions`, everything between
    them is set back to exact silence (the band limit rings a little into the gaps)."""
    import numpy as np

    x = np.asarray(buf, dtype=np.float64)
    n_out = int(round(len(x) * rate / SR))
    spectrum = np.fft.rfft(x)
    y = np.fft.irfft(spectrum[: n_out // 2 + 1], n_out) * (n_out / len(x))
    if regions:
        keep = np.zeros(n_out, dtype=bool)
        for start, length in regions.values():
            a = max(0, int(start * rate))
            b = min(n_out, int((start + length) * rate))
            keep[a:b] = True
        y[~keep] = 0.0
    return np.clip(y, -1.0, 1.0).tolist()


def settle(buf):
    """Strip DC (a 30 Hz high-pass) and fade the last 3 ms so a voice starts and ends at rest."""
    import numpy as np

    x = np.asarray(buf, dtype=np.float64)
    if len(x) == 0:
        return buf
    a = math.exp(-2 * math.pi * 30 / SR)
    y = np.empty_like(x)
    prev_x = prev_y = 0.0
    for i, v in enumerate(x):
        prev_y = a * (prev_y + v - prev_x)
        prev_x = v
        y[i] = prev_y
    tail = min(len(y), int(0.003 * SR))
    if tail > 0:
        y[-tail:] *= np.linspace(1.0, 0.0, tail)
    return y.tolist()


def pack(render, names, gap=GAP, clean=False):
    sheet = zeros(gap)
    regions = {}
    levels = {}
    for name in names:
        started = time.time()
        buf = render(name)
        if clean:
            buf = settle(buf)
        start = len(sheet) / SR
        mix(sheet, buf, start)
        sheet.extend(zeros(gap))
        regions[name] = [round(start, 4), round(len(buf) / SR, 4)]
        levels[name] = loudness(buf)
        print(f"  {name:<18} {len(buf) / SR:5.2f}s  {levels[name]:6.1f} dB  ({time.time() - started:4.1f}s to render)")
    return sheet, regions, levels


def load_ids():
    if os.path.exists(IDS):
        with open(IDS, "r", encoding="utf-8") as f:
            return json.load(f)
    return {"SoundSheet": 0, "Ambience": 0, "Kit": 0}


def lua_number(value):
    return f"{value:.4f}".rstrip("0").rstrip(".") if isinstance(value, float) else str(value)


def write_manifest(build, ids):
    lines = [
        "--!strict",
        "-- GENERATED by tools/assetgen/build.py -- do not edit by hand.",
        "-- Regions, lengths and sizes come from the generated files; the ids come",
        "-- from assets/asset_ids.json (filled in by tools/assetgen/upload.py). An id",
        "-- of 0 means that file hasn't been uploaded yet, and the game falls back to",
        "-- its built-in sounds and part-built models.",
        "",
        "export type Region = { number } -- { start seconds, length seconds }",
        "",
        "local Manifest = {}",
        "",
    ]

    def regions_block(title, data, sheet_id):
        lines.append(f"Manifest.{title} = {{")
        lines.append(f"\tId = {int(sheet_id)},")
        lines.append(f"\tLength = {lua_number(data['length'])},")
        lines.append("\tRegions = {")
        for name, (start, length) in data["regions"].items():
            lines.append(f"\t\t{name} = {{ {lua_number(start)}, {lua_number(length)} }},")
        lines.append("\t} :: { [string]: Region },")
        lines.append("\t-- Loudness of each entry (dB RMS while sounding), for level matching.")
        lines.append("\tLoudness = {")
        for name, level in data.get("loudness", {}).items():
            lines.append(f"\t\t{name} = {lua_number(float(level))},")
        lines.append("\t} :: { [string]: number },")
        lines.append("}")
        lines.append("")

    regions_block("SoundSheet", build["sfx"], ids.get("SoundSheet", 0))
    if build.get("sfx_previous") and ids.get("SoundSheetPrevious"):
        regions_block("SoundSheetPrevious", build["sfx_previous"], ids["SoundSheetPrevious"])
    regions_block("Ambience", build["ambience"], ids.get("Ambience", 0))
    lines.append("Manifest.Kit = {")
    lines.append(f"\tId = {int(ids.get('Kit', 0))},")
    lines.append(f"\tPlaceholderId = {int(ids.get('KitPlaceholder', 0))},")
    lines.append(f"\tKitReady = {str(bool(ids.get('KitReady', False))).lower()},")
    lines.append("\t-- Native size of each model (studs, as generated). The game sets")
    lines.append("\t-- MeshPart.Size itself; these keep proportions when it scales one axis.")
    lines.append("\tSizes = {")
    for name, (x, y, z) in build["kit"]["sizes"].items():
        lines.append(f"\t\t{name} = Vector3.new({lua_number(x)}, {lua_number(y)}, {lua_number(z)}),")
    lines.append("\t} :: { [string]: Vector3 },")
    lines.append("}")
    lines.append("")
    lines.append("return Manifest")
    # The manifest is the AssetManifest member of the merged SharedData suite: replace that member's body.
    body = [line for line in lines if not line.lstrip().startswith("--")]
    body = [("type Region = { number }" if line.startswith("export type Region") else line) for line in body]
    while body and body[0] == "":
        body.pop(0)
    with open(SUITE, "r", encoding="utf-8", newline="") as f:
        suite = f.read()
    newline = "\r\n" if "\r\n" in suite else "\n"
    header = '__defs["AssetManifest"] = function()'
    start = suite.find(header)
    if start < 0:
        sys.exit("SharedData has no AssetManifest member")
    body_start = suite.find(newline, start) + len(newline)
    stop = suite.find(newline + "__defs[", body_start)
    if stop < 0:
        sys.exit("AssetManifest is not followed by another member")
    member = newline + newline.join(body) + newline + "end" + newline
    suite = suite[:body_start] + member + suite[stop:]
    with open(SUITE, "w", encoding="utf-8", newline="") as f:
        f.write(suite)
    print(f"wrote the AssetManifest member of {os.path.relpath(SUITE, ROOT)}")


def main():
    os.makedirs(OUT, exist_ok=True)
    build_path = os.path.join(OUT, "build.json")
    build = {}
    if os.path.exists(build_path):
        with open(build_path, "r", encoding="utf-8") as f:
            build = json.load(f)
    if "--manifest" in sys.argv:
        write_manifest(build, load_ids())
        return
    only = sys.argv[sys.argv.index("--only") + 1] if "--only" in sys.argv else None

    if "--rotate-sfx" in sys.argv:
        # Keep the live sheet as the fallback the game plays until the new upload clears moderation.
        ids = load_ids()
        if ids.get("SoundSheet") and build.get("sfx"):
            build["sfx_previous"] = build["sfx"]
            ids["SoundSheetPrevious"] = ids["SoundSheet"]
            ids["SoundSheet"] = 0
            with open(IDS, "w", encoding="utf-8") as f:
                json.dump(ids, f, indent=2)
            print(f"kept sheet {ids['SoundSheetPrevious']} as the fallback; the next upload replaces it")
    if only in (None, "sfx"):
        print("sound sheet:")
        sheet, regions, levels = pack(sfx.render, list(sfx.VOICES), SFX_GAP, clean=True)
        write_wav(os.path.join(OUT, "AstralForgeSFX.wav"), resample(sheet, SFX_RATE, regions), SFX_RATE)
        build["sfx"] = {"length": round(len(sheet) / SR, 3), "regions": regions, "loudness": levels}

    if only in (None, "ambience"):
        print("ambience sheet:")
        amb, amb_regions, amb_levels = pack(ambience.render, list(ambience.LOOPS))
        write_wav(os.path.join(OUT, "AstralForgeAmbience.wav"), amb)
        build["ambience"] = {"length": round(len(amb) / SR, 3), "regions": amb_regions, "loudness": amb_levels}

    if only in (None, "kit"):
        print("model kit:")
        built = [(name, make()) for name, make in meshes.MODELS.items()]
        for name, mesh in built:
            print(f"  {name:<14} {len(mesh.tris):5d} triangles")
        build["kit"] = {"sizes": meshes.write_glb(os.path.join(OUT, "AstralForgeKit.glb"), built)}

    with open(build_path, "w", encoding="utf-8") as f:
        json.dump(build, f, indent=2)
    write_manifest(build, load_ids())


if __name__ == "__main__":
    main()
